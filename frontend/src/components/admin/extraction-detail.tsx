"use client";
import Link from "next/link";
import { useEffect, useState } from "react";
import {
  adminFetch,
  type Candidate,
  type ProcessingJob,
  type ResultPage,
} from "@/lib/admin";
import { ErrorState, LoadingState } from "@/components/ui";
import { EvidenceViewer } from "./evidence";

export function ExtractionDetail({ id }: { id: string }) {
  const [job, setJob] = useState<ProcessingJob | null>(null);
  const [candidates, setCandidates] = useState<ResultPage<Candidate> | null>(
    null,
  );
  const [error, setError] = useState("");
  const [page, setPage] = useState(1);
  const [refresh, setRefresh] = useState(0);
  const [evidence, setEvidence] = useState<{
    page: number;
    excerpt: string;
  } | null>(null);
  useEffect(() => {
    const controller = new AbortController();
    Promise.all([
      adminFetch<ProcessingJob>(`extractions/${id}`, {
        signal: controller.signal,
      }),
      adminFetch<ResultPage<Candidate>>(
        `extractions/${id}/candidates?page=${page}`,
        { signal: controller.signal },
      ),
    ])
      .then(([result, items]) => {
        if (controller.signal.aborted) return;
        setJob(result);
        setCandidates(items);
      })
      .catch((reason: Error) => {
        if (!controller.signal.aborted) setError(reason.message);
      });
    return () => controller.abort();
  }, [id, page, refresh]);
  if (error)
    return (
      <ErrorState
        message={error}
        retry={() => {
          setError("");
          setRefresh((value) => value + 1);
        }}
      />
    );
  if (!job || !candidates)
    return <LoadingState message="Loading extraction evidence…" />;
  return (
    <>
      <section className="admin-card">
        <Link
          className="text-link"
          href={`/admin/documents/${job.document_version_id}`}
        >
          ← Source document
        </Link>
        <p className="eyebrow">{job.status}</p>
        <h2>Candidate rule review</h2>
        <p>
          Provider: <strong>{job.provider}</strong> · Model:{" "}
          {job.model || "Text extraction only"} · {job.input_chunk_count} input
          chunks selected
        </p>
        {job.provider === "fixture" && (
          <p className="notice">
            Supervised mock demonstration. These candidates were generated by a
            deterministic fixture, using a real official PDF. Gemini was not
            called.
          </p>
        )}
        <p>
          Every candidate remains <strong>PENDING</strong>. A validation result
          confirms technical checks only; it does not approve a government rule.
        </p>
        {job.errors?.length ? (
          <div className="admin-errors">
            <h3>Processing issues</h3>
            <ul>
              {job.errors.map((item, index) => (
                <li key={`${item.code}-${index}`}>
                  <strong>{item.code}</strong>: {item.message}
                  {item.page_number ? ` (page ${item.page_number})` : ""}
                </li>
              ))}
            </ul>
          </div>
        ) : null}
        {job.status === "RUNNING" && (
          <button
            className="button button-secondary"
            onClick={() => setRefresh((value) => value + 1)}
          >
            Refresh status
          </button>
        )}
      </section>
      {!candidates.items.length && (
        <section className="admin-card">
          <p>
            No candidate rules stored for this extraction. Review the processing
            status and issues.
          </p>
        </section>
      )}
      {candidates.items.map((candidate) => (
        <section className="admin-card" key={candidate.id}>
          <div className="admin-candidate-heading">
            <div>
              <span className="eyebrow">
                {candidate.review_status} · {candidate.validation_status}
              </span>
              <h2>{candidate.label}</h2>
            </div>
            <code>{candidate.condition_identifier}</code>
          </div>
          <p className="small-note">
            Relationship within its extraction batch:{" "}
            {candidate.logical_relationship}. Source document version:{" "}
            {candidate.document_version_id}
          </p>
          {candidate.validation_issues.length > 0 && (
            <ul className="admin-errors">
              {candidate.validation_issues.map((issue, index) => (
                <li key={index}>{issue}</li>
              ))}
            </ul>
          )}
          <h3>Candidate conditions</h3>
          {!!candidate.payload.extraction_uncertainty?.length && (
            <div className="admin-errors">
              <h3>Extraction uncertainty</h3>
              <ul>
                {candidate.payload.extraction_uncertainty.map(
                  (uncertainty, index) => (
                    <li key={index}>{uncertainty}</li>
                  ),
                )}
              </ul>
            </div>
          )}
          <div className="admin-table-wrap">
            <table>
              <thead>
                <tr>
                  <th>Node</th>
                  <th>Field / expression</th>
                  <th>Operator</th>
                  <th>Proposed value</th>
                  <th>Units</th>
                </tr>
              </thead>
              <tbody>
                {candidate.payload.nodes.map((node) => (
                  <tr key={node.key}>
                    <td>{node.key}</td>
                    <td>{node.field || node.kind}</td>
                    <td>{node.operator || "—"}</td>
                    <td>
                      <code>{JSON.stringify(node.expected_value)}</code>
                      {node.children.length > 0 &&
                        ` (${node.children.join(", ")})`}
                    </td>
                    <td>{node.units || "—"}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
          <h3>Supporting evidence</h3>
          {candidate.evidence.length ? (
            candidate.evidence.map((item, index) => (
              <div className="admin-quote" key={index}>
                <blockquote>{item.excerpt}</blockquote>
                <button
                  className="text-link"
                  onClick={() =>
                    setEvidence({
                      page: item.page_number,
                      excerpt: item.excerpt,
                    })
                  }
                >
                  Inspect page {item.page_number} · {item.node_key}
                </button>
              </div>
            ))
          ) : (
            <p>
              Evidence is missing or could not be located. Manual review is
              required.
            </p>
          )}
          <details>
            <summary>Deterministic expression preview</summary>
            <pre className="admin-page-text">
              {JSON.stringify(candidate.mapped_expression, null, 2)}
            </pre>
          </details>
        </section>
      ))}
      {candidates.total > candidates.page_size && (
        <nav className="pagination" aria-label="Candidate pagination">
          <button
            className="button button-secondary"
            disabled={page === 1}
            onClick={() => setPage((value) => value - 1)}
          >
            Previous
          </button>
          <span>Page {page}</span>
          <button
            className="button button-secondary"
            disabled={page * candidates.page_size >= candidates.total}
            onClick={() => setPage((value) => value + 1)}
          >
            Next
          </button>
        </nav>
      )}
      {evidence && (
        <section className="admin-card">
          <button className="text-link" onClick={() => setEvidence(null)}>
            Close evidence
          </button>
          <EvidenceViewer
            documentId={job.document_version_id}
            pageNumber={evidence.page}
            excerpt={evidence.excerpt}
          />
        </section>
      )}
    </>
  );
}
